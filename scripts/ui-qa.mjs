import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const folder = new URL('../docs/screenshots/', import.meta.url);
await mkdir(folder, { recursive: true });
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1100 }, deviceScaleFactor: 1 });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto('http://127.0.0.1:3000', { waitUntil: 'networkidle' });
await page.getByRole('heading', { name: '어떤 주제를 찾고 있나요?' }).waitFor();
await page.getByText('Chrome 확장 프로그램 설치를 확인해 주세요', { exact: true }).waitFor({ timeout: 10000 });
await page.screenshot({ path: new URL('home-desktop.png', folder).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
await page.getByText('샘플로 둘러보기', { exact: false }).click();
await page.getByRole('button', { name: '데모 프로젝트 열기' }).click();
await page.waitForURL(/\/projects\//);
await page.getByText('합성 검색 샘플에서 필터링').waitFor();
await page.screenshot({ path: new URL('dashboard-desktop.png', folder).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
await page.getByText('합성 검색 샘플에서 필터링').click();
await page.getByRole('button', { name: '샘플 분석', exact: true }).click();
await page.getByText(/개 결과 분석 완료/).waitFor({ timeout: 30000 });
await page.screenshot({ path: new URL('demo-desktop.png', folder).pathname.replace(/^\/(\w:)/, '$1'), fullPage: false });
await page.getByRole('link', { name: '필기 정리', exact: true }).click();
await page.getByRole('heading', { name: '필기 정리', exact: true }).waitFor();
await page.screenshot({ path: new URL('notes-desktop.png', folder).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
await page.getByRole('link', { name: '사용 기록', exact: true }).click();
await page.getByRole('heading', { name: '사용 기록', exact: true }).waitFor();
await page.screenshot({ path: new URL('report-desktop.png', folder).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
await page.goto('http://127.0.0.1:3000/settings', { waitUntil: 'networkidle' });
await page.getByRole('heading', { name: '설정', exact: true }).waitFor();
await page.screenshot({ path: new URL('settings-desktop.png', folder).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true });
const mobilePage = await mobile.newPage();
mobilePage.on('pageerror', error => errors.push(error.message));
await mobilePage.goto('http://127.0.0.1:3000', { waitUntil: 'networkidle' });
await mobilePage.getByRole('heading', { name: '어떤 주제를 찾고 있나요?' }).waitFor();
await mobilePage.getByText('Chrome 확장 프로그램 설치를 확인해 주세요', { exact: true }).waitFor({ timeout: 10000 });
await mobilePage.screenshot({ path: new URL('home-mobile.png', folder).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
const overflowPages = [];
if (await mobilePage.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)) overflowPages.push('home');
await mobilePage.goto('http://127.0.0.1:3000/settings', { waitUntil: 'networkidle' });
await mobilePage.getByRole('heading', { name: '설정', exact: true }).waitFor();
await mobilePage.screenshot({ path: new URL('settings-mobile.png', folder).pathname.replace(/^\/(\w:)/, '$1'), fullPage: true });
if (await mobilePage.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)) overflowPages.push('settings');
const overflow = overflowPages.length > 0;
await writeFile(new URL('ui-checks.json', folder), JSON.stringify({ browserErrors: errors, mobileOverflow: overflow, overflowPages, checkedAt: new Date().toISOString() }, null, 2));
await browser.close();
console.log(JSON.stringify({ browserErrors: errors, mobileOverflow: overflow }));
if (errors.length || overflow) process.exitCode = 1;
